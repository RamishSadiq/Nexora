using System.Linq.Expressions;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
namespace Nexora.BuildingBlocks.Persistence;

public class DataAuditEntry
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid? TenantId { get; set; }
    public string EntityId { get; set; } = "";
    public Guid? ParentId { get; set; }
    public Guid? OtherParentId { get; set; }
    public DateTime ChangedAtUtc { get; set; } = DateTime.UtcNow;
    public string Operation { get; set; } = "";
    public string ChangesJson { get; set; } = "[]";
}
public sealed class DataAudit<T> : DataAuditEntry where T : class { }
public sealed record DataAuditChange(string Field, object? Previous, object? Current);
public static class DataAuditModel
{
    public static void Configure(ModelBuilder builder, Expression<Func<Guid?>> tenant)
    {
        var sources = builder.Model.GetEntityTypes().Where(e => !e.IsOwned() && !typeof(DataAuditEntry).IsAssignableFrom(e.ClrType) && e.FindPrimaryKey() != null).ToArray();
        foreach (var source in sources)
        {
            var type = typeof(DataAudit<>).MakeGenericType(source.ClrType);
            var audit = builder.Entity(type); audit.HasBaseType((Type?)null);
            audit.ToTable(source.GetTableName() + "DataAudit", source.GetSchema());
            audit.HasKey(nameof(DataAuditEntry.Id));
            audit.Property(nameof(DataAuditEntry.EntityId)).HasMaxLength(400);
            audit.Property(nameof(DataAuditEntry.Operation)).HasMaxLength(12);
            audit.Property(nameof(DataAuditEntry.ChangesJson)).IsRequired();
            audit.Property(nameof(DataAuditEntry.ChangedAtUtc)).HasConversion(new ValueConverter<DateTime,DateTime>(v=>v,v=>DateTime.SpecifyKind(v,DateTimeKind.Utc)));
            audit.HasIndex(nameof(DataAuditEntry.TenantId), nameof(DataAuditEntry.EntityId), nameof(DataAuditEntry.ChangedAtUtc));
            audit.HasIndex(nameof(DataAuditEntry.TenantId), nameof(DataAuditEntry.ParentId), nameof(DataAuditEntry.ChangedAtUtc));
            var parameter = Expression.Parameter(type, "a");
            audit.HasQueryFilter(Expression.Lambda(Expression.AndAlso(Expression.NotEqual(tenant.Body,Expression.Constant(null,typeof(Guid?))), Expression.Equal(Expression.Property(parameter,nameof(DataAuditEntry.TenantId)),tenant.Body)),parameter));
        }
        builder.Ignore<DataAuditEntry>();
    }
}
// Runs after domain guards and automation. Audit rows participate in the same SaveChanges transaction.
public sealed class DataAuditInterceptor(Func<Guid?> tenant) : SaveChangesInterceptor
{
    private readonly HashSet<object> generated = new(ReferenceEqualityComparer.Instance);
    public override InterceptionResult<int> SavingChanges(DbContextEventData e, InterceptionResult<int> result) { Capture(e.Context!,default).GetAwaiter().GetResult(); return result; }
    public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(DbContextEventData e, InterceptionResult<int> result, CancellationToken ct=default) { await Capture(e.Context!,ct); return result; }
    private async Task Capture(DbContext db,CancellationToken ct)
    {
        db.ChangeTracker.DetectChanges();
        foreach(var entry in db.ChangeTracker.Entries().Where(e=>e.Entity is DataAuditEntry).ToArray())
        {
            if(entry.State==EntityState.Unchanged)continue;
            if(entry.State==EntityState.Added && generated.Contains(entry.Entity)) entry.State=EntityState.Detached;
            else throw new InvalidOperationException("Data audit is append-only and generated by the system.");
        }
        generated.Clear();
        foreach(var entry in db.ChangeTracker.Entries().Where(e=>e.Entity is not DataAuditEntry && e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted).ToArray())
        {
            var type=typeof(DataAudit<>).MakeGenericType(entry.Metadata.ClrType);
            if(db.Model.FindEntityType(type)==null)continue;
            var stored=entry.State==EntityState.Added?null:await entry.GetDatabaseValuesAsync(ct);
            var changes=new List<DataAuditChange>();
            foreach(var p in entry.Properties)
            {
                if(p.Metadata.Name is "Version" or "UpdatedAtUtc" or "ConcurrencyStamp" or "SecurityStamp")continue;
                var before=stored?[p.Metadata.Name]; var after=entry.State==EntityState.Deleted?null:p.CurrentValue;
                if(Equals(before,after) || before is byte[] b && after is byte[] a && b.SequenceEqual(a))continue;
                var name=p.Metadata.Name;
                var sensitive=p.Metadata.ClrType==typeof(byte[]) || new[]{"password","secret","token","credential","json","hash","sha256"}.Any(s=>name.Contains(s,StringComparison.OrdinalIgnoreCase));
                // Identity token values have a generic Value field.
                sensitive |= entry.Metadata.ClrType.Name.Contains("Token",StringComparison.OrdinalIgnoreCase) && name=="Value";
                changes.Add(new(name,sensitive&&before!=null?"[redacted]":before,sensitive&&after!=null?"[redacted]":after));
            }
            if(changes.Count==0)continue;
            object? Value(string name)=>entry.Metadata.FindProperty(name)==null?null:entry.State==EntityState.Deleted?stored?[name]:entry.Property(name).CurrentValue;
            var audit=(DataAuditEntry)Activator.CreateInstance(type)!;
            audit.TenantId=Value("TenantId") as Guid? ?? tenant();
            audit.EntityId=string.Join("|",entry.Metadata.FindPrimaryKey()!.Properties.Select(p=>Value(p.Name)?.ToString()));
            if(audit.EntityId.Length>400) audit.EntityId="sha256:"+Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(audit.EntityId)));
            audit.ParentId=(Value("RecordId")??Value("ContactId")??Value("ApplicationId")??Value("OfferingId")) as Guid?;
            audit.OtherParentId=(Value("AccountId")??Value("TargetRecordId")) as Guid?;
            if(Value("AssociationId") is Guid associationId)
            {
                var parentType=db.Model.GetEntityTypes().FirstOrDefault(t=>t.ClrType.Name=="AccountContact");
                if(parentType!=null && await db.FindAsync(parentType.ClrType,[associationId],ct) is object parent)
                {
                    var association=db.Entry(parent);
                    if(Equals(association.Property("TenantId").CurrentValue,audit.TenantId)) { audit.ParentId=association.Property("ContactId").CurrentValue as Guid?; audit.OtherParentId=association.Property("AccountId").CurrentValue as Guid?; }
                }
            }
            audit.Operation=entry.State.ToString();audit.ChangesJson=JsonSerializer.Serialize(changes);
            generated.Add(audit);db.Add(audit);
        }
    }
}
