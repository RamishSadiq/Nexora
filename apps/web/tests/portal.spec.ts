import { test, expect } from "@playwright/test";
import { randomBytes } from "node:crypto";

test("organisation permission, application receipt and live revocation", async ({ page, browser }) => {
  const staff = await browser.newContext();
  const request = staff.request;
  async function send(path: string, data?: unknown, method = "POST") {
    const token = await (await request.get("/api/v1/auth/csrf")).json();
    const response = await request.fetch(path, { method, data, headers: { "X-CSRF-TOKEN": token.token } });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.status() === 204 ? null : response.json();
  }
  await send("/api/v1/auth/login", { email: "admin@nexora.local", password: process.env.NEXORA_BROWSER_PASSWORD, rememberMe: false });
  const contact = await send("/api/v1/crm/records", { kind: "contact", name: "Company Representative", status: "active" });
  const company = await send("/api/v1/crm/records", { kind: "account", name: "Portal Company", status: "active" });
  await send(`/api/v1/crm/accounts/${company.id}/contacts`, { contactId: contact.id, startDate: new Date().toISOString().slice(0,10), jobTitle: "Director", workClassification: "technical", isMainContact: true, isAuthorisedContact: true, roles: ["membership"] });
  const password = `Member!${randomBytes(16).toString("hex")}`;
  const access = await send("/api/v1/admin/portal-access/local-member", { contactId: contact.id, email: "company.member@nexora.test", password });
  const product = await send("/api/v1/membership/products", { name: "Company annual membership", category: "corporate", termMonths: 12, rate: 0, currency: "GBP", isActive: true });
  const staffPage = await staff.newPage();
  await staffPage.goto("/membership");
  await staffPage.getByRole("button", { name: "Products", exact: true }).click();
  await staffPage.getByLabel("Portal product", { exact: true }).selectOption(product.id);
  await staffPage.getByLabel("Allow organisation applications in the member portal").check();
  await staffPage.getByLabel("Member-facing terms").fill("Company application terms.");
  await staffPage.getByRole("button", { name: "Save portal settings" }).click();
  await expect(staffPage.getByRole("status").filter({ hasText: "Portal settings saved" })).toBeVisible();
  await page.goto("/portal");
  await page.getByLabel("Email", { exact: true }).fill("company.member@nexora.test");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("navigation", { name: "Member navigation" }).getByRole("link", { name: "My organisations", exact: true }).click();
  await expect(page.getByText("No organisation access has been granted.")).toBeVisible();
  await staffPage.goto("/settings");
  const record = staffPage.getByRole("article").filter({ hasText: "company.member@nexora.test" });
  await record.getByLabel("Find an organisation", { exact: true }).fill("Portal Company");
  await record.getByRole("button", { name: "Search organisations", exact: true }).click();
  await record.getByLabel("Grant organisation", { exact: true }).selectOption(company.id);
  await record.getByLabel("Allow membership applications", { exact: true }).check();
  await record.getByRole("button", { name: "Grant organisation permission", exact: true }).click();
  await expect(record.getByText("View and apply", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Refresh organisations", exact: true }).click();
  await page.getByLabel("Organisation", { exact: true }).selectOption(company.id);
  const workspace = page.getByRole("region", { name: "Organisation membership application", exact: true });
  await workspace.getByRole("button", { name: "New application", exact: true }).click();
  await workspace.getByLabel("Membership product").selectOption(product.id);
  await workspace.getByLabel("Application notes").fill("Company submission evidence summary");
  await workspace.getByRole("button", { name: "Save and review draft" }).click();
  await workspace.getByLabel("I accept these membership terms.").check();
  await workspace.getByRole("button", { name: "Submit application", exact: true }).click();
  await page.getByRole("link", { name: "View company application receipt", exact: true }).click();
  await expect(page.getByText("Company application terms.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Company submission evidence summary", { exact: true })).toBeVisible();
  const applicationId = new URL(page.url()).pathname.split("/").at(-1);
  const applications = await (await request.get("/api/v1/membership/applications")).json();
  const application = applications.items.find((a: { id: string }) => a.id === applicationId);
  await send(`/api/v1/membership/applications/${application.id}/decision`, { version: application.version, decision: "approve", reason: "Private company review" });
  await page.getByRole("button", { name: "Refresh application status" }).click();
  await expect(page.getByRole("region", { name: "Resulting membership" })).toContainText("active");
  await expect(page.getByText("Private company review")).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: "../../portal-company-receipt-mobile.png", fullPage: true });
  await record.getByRole("button", { name: "Revoke organisation permission", exact: true }).click();
  await record.getByRole("button", { name: "Confirm organisation revocation", exact: true }).click();
  await expect(record.getByText("Revoked", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Refresh application status" }).click();
  await expect(page.getByRole("region", { name: "Resulting membership" })).toHaveCount(0);
  expect((await page.request.get(`/api/v1/portal/organisations/${company.id}/memberships`)).status()).toBe(404);
  expect((await request.get(`/api/v1/admin/portal-access/${access.id}/organisations`)).ok()).toBeTruthy();
  await staff.close();
});

